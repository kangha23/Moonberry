#!/usr/bin/env node
/**
 * Turns the contents of `public/assets/lpc/` into something the game can read.
 *
 * The folder used to be listed twice: once as files on disk, and once as a
 * hand-maintained array in `FarmScene.preload` — plus a third list of which
 * crops had a drawing, and a fourth in the villager type saying which walk
 * sheets exist. Adding one PNG meant editing four places, and forgetting one
 * of them meant either eleven load errors on every boot or a drawing nobody
 * ever sees.
 *
 * So the folder is the list. Drop a file in, run this, and the loader, the
 * crop renderer, the villager animations and the `LpcSheet` type all know
 * about it. Take a file out and they all stop asking for it.
 *
 * The same arrangement as `build-maps.mjs`: a generated module, committed, so
 * nothing has to scan a directory at runtime.
 */
import fs from 'node:fs';
import path from 'node:path';

const ART_DIR = path.join('public', 'assets', 'lpc');
const OUT_FILE = path.join('src', 'game', 'assets', 'lpc.generated.ts');
const ITEMS_FILE = path.join('src', 'game', 'systems', 'items.ts');

/** Growth stages every crop shares. Named `crop-*`, but not crops. */
const CROP_STAGES = ['seeded', 'sprout'];

/** What the loader wants but the folder may not have, so the run can say so. */
const CORE_IMAGES = [
  'tile-grass',
  'tile-path',
  'tile-water',
  'plot-wild',
  'plot-tilled',
  'plot-watered',
  'crop-seeded',
  'crop-sprout',
  'grass-tuft',
  'tree',
  'farmhouse',
];

/**
 * The crop ids, read from the source of truth rather than copied next to it.
 *
 * A crop list that drifts from `items.ts` would report a perfectly good
 * drawing as an unknown file, which is worse than not checking at all.
 */
function cropIds() {
  const source = fs.readFileSync(ITEMS_FILE, 'utf8');
  const block = source.match(/export const CROP_ORDER: readonly CropId\[\] = \[([\s\S]*?)\n\];/);
  if (!block) throw new Error(`Could not find CROP_ORDER in ${ITEMS_FILE}.`);
  return [...block[1].matchAll(/'([a-z0-9-]+)'/g)].map((match) => match[1]);
}

const crops = cropIds();
const files = fs
  .readdirSync(ART_DIR)
  .filter((file) => file.endsWith('.png'))
  .map((file) => file.slice(0, -4))
  .sort();

const sheets = files.filter((name) => name.endsWith('-sheet'));
const images = files.filter((name) => !name.endsWith('-sheet'));

// A `crop-*.png` that is neither a stage nor a crop is almost always a typo in
// a file name, and it would otherwise fail as a type error in the generated
// file with no hint about which file caused it.
const strays = images
  .filter((name) => name.startsWith('crop-'))
  .map((name) => name.slice('crop-'.length))
  .filter((id) => !CROP_STAGES.includes(id) && !crops.includes(id));
for (const id of strays) {
  console.warn(
    `warning: ${ART_DIR}/crop-${id}.png does not match any crop in ${ITEMS_FILE}. ` +
      'It will load, but nothing draws it. Check the spelling against CROP_ORDER.',
  );
}

const drawnCrops = crops.filter((id) => images.includes(`crop-${id}`));

const banner = `// Generated by scripts/generate-lpc-manifest.mjs from public/assets/lpc/*.png.
// Do not edit by hand: add or remove a PNG in that folder and run
// "npm run lpc:manifest". See public/assets/lpc/CREDITS.md for what the art is
// and what it is licensed under.
import type { CropId } from '../systems/items';
`;

// An empty folder would make the union \`never\`, which turns one missing file
// into an error on every villager instead of one on the sheet that is gone.
const sheetType = sheets.length
  ? `export type LpcSheet = (typeof LPC_SHEETS)[number];`
  : `// No walk sheets in the folder, so anything typechecks and nothing loads.\nexport type LpcSheet = string;`;

const body = `
/**
 * Every plain image in the art folder, as [texture key, url].
 *
 * The key is the file name, which is what the scene already called it. A file
 * that is not here is not missing art — the procedural textures in
 * \`createPixelArtTextures\` stand in for it — so this list is exactly what
 * should be requested over the network, and nothing else.
 */
export const LPC_IMAGES: readonly (readonly [key: string, url: string])[] = [
${images.map((name) => `  ['${name}', '/assets/lpc/${name}.png'],`).join('\n')}
];

/**
 * The walk sheets, read as nine frames across and four directions down, at
 * 64px each. Row order is the LPC convention: up, left, down, right.
 */
export const LPC_SHEETS = [${sheets.map((name) => `'${name}'`).join(', ')}] as const;

${sheetType}

/**
 * Crops with a hand-drawn ripe sprite. The rest grow the generated plants in
 * \`createPixelArtTextures\`, which is the arrangement, not a gap to apologise
 * for — but every id that moves out of that fallback and into this list is the
 * game looking more like itself.
 */
export const LPC_CROPS: readonly CropId[] = [${drawnCrops.map((id) => `'${id}'`).join(', ')}];
`;

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, `${banner}${body}`);

console.log(`wrote ${OUT_FILE}`);
console.log(`  images ${images.length}, sheets ${sheets.length} (${sheets.join(', ') || 'none'})`);
console.log(`  crops drawn ${drawnCrops.length}/${crops.length}: ${drawnCrops.join(', ') || 'none'}`);

const missingCrops = crops.filter((id) => !drawnCrops.includes(id));
if (missingCrops.length) console.log(`  crops still generated: ${missingCrops.join(', ')}`);
const missingCore = CORE_IMAGES.filter((name) => !images.includes(name));
if (missingCore.length) console.log(`  missing, falling back to generated art: ${missingCore.join(', ')}`);
