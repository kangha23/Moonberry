#!/usr/bin/env node
/**
 * Turns `art/palette.json` into the module the app imports.
 *
 * Two runtimes need the same 48 colours: these build scripts, which are plain
 * ESM under Node, and the game, which is TypeScript through Vite. Node cannot
 * import a `.ts` module without a loader, and keeping two hand-written copies
 * is how a palette stops being one palette. So the JSON is the data and this
 * writes the typed view of it.
 *
 * Run: npm run palette:module
 */
import fs from 'node:fs';
import path from 'node:path';

const IN_FILE = path.join('art', 'palette.json');
const OUT_FILE = path.join('src', 'game', 'assets', 'palette.generated.ts');

const { colours } = JSON.parse(fs.readFileSync(IN_FILE, 'utf8'));

const entries = colours.map((c) => `  '${c.name}': '${c.hex}',`).join('\n');

fs.writeFileSync(
  OUT_FILE,
  `// Generated by scripts/generate-palette-module.mjs from art/palette.json.
// Do not edit by hand: change art/palette.json and run "npm run palette:module".
//
// Every colour the game draws comes from here. A hex literal anywhere in src/
// or scripts/ fails the test in scripts/palette-lock.test.mjs, which is what
// keeps this file meaningful rather than decorative.

/** Every colour in the game, as ramp.step. */
export const PALETTE = {
${entries}
} as const;

/**
 * The name of any colour. A hex string is not a colour; this is.
 *
 * Derived from PALETTE's own keys (\`keyof typeof PALETTE\`) rather than
 * written out as a second, hand-duplicated list of the same 48 names. Both
 * used to come from one pass over \`colours\` in this generator, which kept
 * them in sync as long as nobody touched one without the other — but that
 * is a rule a future edit to this file could break without anyone noticing,
 * since a stale union would still typecheck against whatever names remained
 * in PALETTE, just silently reject any name added after it went stale.
 * Deriving the type from the value it names removes the chance to desync.
 */
export type PaletteName = keyof typeof PALETTE;

/** The same colours as a flat list, for the quantiser and the lock test. */
export const PALETTE_HEXES: readonly string[] = Object.values(PALETTE);

/**
 * A colour as the integer Phaser tints with.
 *
 * Phaser wants 0xRRGGBB and the palette stores '#rrggbb'. Converting at the
 * call site is how 0x literals creep back in, so it happens here instead.
 */
export function tint(name: PaletteName): number {
  return Number.parseInt(PALETTE[name].slice(1), 16);
}
`,
);

console.log(`wrote ${OUT_FILE} — ${colours.length} colours`);
